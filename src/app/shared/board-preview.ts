import { NgTemplateOutlet } from '@angular/common';
import { ChangeDetectionStrategy, Component, computed, inject, input } from '@angular/core';
import { BoardCell, BoardSnapshot } from '../core/ai/board-snapshot';
import { handText, interruptionText } from '../core/ai/evaluate';
import { CardNamesService } from '../core/card-names.service';
import { CardCount, CardRecord, FieldSlot, LinkMarker } from '../core/models';
import { CardTile } from './card-tile';

const GLYPH: Record<LinkMarker, string> = { Top: '▲', Bottom: '▼', Left: '◀', Right: '▶', 'Top-Left': '◤', 'Top-Right': '◥', 'Bottom-Left': '◣', 'Bottom-Right': '◢' };
const EMZ: FieldSlot[] = ['EMZ-L', 'EMZ-R'];
const MMZ: FieldSlot[] = ['M1', 'M2', 'M3', 'M4', 'M5'];
const SZ: FieldSlot[] = ['S1', 'S2', 'S3', 'S4', 'S5'];

/**
 * CR-008 G51: the end board drawn from a snapshot of the last step — 2 Extra Monster Zones, 5 Main
 * Monster Zones, 5 Spell/Trap Zones and the Field Zone, card images and names, Link arrows and
 * co-link marks, and (full size) the Graveyard, banished zone, hand, Deck and Extra Deck counts,
 * interruptions and follow-up resources. Nothing here is generated by a model.
 */
@Component({
  selector: 'app-board-preview',
  imports: [CardTile, NgTemplateOutlet],
  template: `
    <div class="board" role="group" [attr.aria-label]="label()" [class.compact]="compact()">
      <ng-template #cellTpl let-slot let-cell="cell">
        <div class="cell" [class.empty]="!cell" [class.colinked]="!!cell && cell.coLinked.length > 0" [attr.data-slot]="slot" [attr.data-colinked]="cell && cell.coLinked.length ? 'true' : 'false'">
          <span class="slot-name" aria-hidden="true">{{ slotLabel(slot) }}</span>
          @if (cell) {
            <app-card-tile [cardId]="cell.cardId" [card]="cards().get(cell.cardId)" size="fit" />
            <span [class.visually-hidden]="compact()" class="cname">{{ name(cell.cardId) }}</span>
            @for (a of cell.arrows; track a) {
              <span class="arrow" [attr.data-dir]="a" aria-hidden="true">{{ glyphOf(a) }}</span>
            }
            @if (cell.coLinked.length) {
              <span class="colink" [attr.title]="'與 ' + cell.coLinked.join('、') + ' 相互連結'">互連</span>
            }
            <span class="visually-hidden">{{ arrowText(cell) }}</span>
          }
        </div>
      </ng-template>

      <div class="grid emz">
        @for (z of emz(); track z.slot) {
          <ng-container [ngTemplateOutlet]="cellTpl" [ngTemplateOutletContext]="{ $implicit: z.slot, cell: z.cell }" />
        }
      </div>
      <div class="grid mmz">
        @for (z of mmz(); track z.slot) {
          <ng-container [ngTemplateOutlet]="cellTpl" [ngTemplateOutletContext]="{ $implicit: z.slot, cell: z.cell }" />
        }
      </div>
      <div class="grid st">
        @for (z of st(); track z.slot) {
          <ng-container [ngTemplateOutlet]="cellTpl" [ngTemplateOutletContext]="{ $implicit: z.slot, cell: z.cell }" />
        }
        <ng-container [ngTemplateOutlet]="cellTpl" [ngTemplateOutletContext]="{ $implicit: 'FZ', cell: snapshot().fieldZone }" />
      </div>

      @if (snapshot().unplaced.length) {
        <p class="note">沒有格子資料（無法標示位置）：{{ names(snapshot().unplaced) }}</p>
      }
      @if (!snapshot().layoutKnown) {
        <p class="note">部分怪獸沒有格子資料，箭頭與相互連結可能不完整。</p>
      }

      @if (!compact()) {
        <dl class="info">
          <dt>墓地（{{ total(snapshot().gy) }}）</dt>
          <dd>{{ list(snapshot().gy) }}</dd>
          <dt>除外（{{ total(snapshot().banished) }}）</dt>
          <dd>{{ list(snapshot().banished) }}</dd>
          <dt>剩餘手牌</dt>
          <dd>{{ list(snapshot().hand) }}・{{ handLabel() }}</dd>
          <dt>牌組・額外牌組</dt>
          <dd>牌組剩 {{ snapshot().deckCount }} 張・額外牌組剩 {{ snapshot().extraCount }} 張</dd>
          <dt>有效干擾（靜態估算）</dt>
          <dd>
            {{ interruptions() }}
            @if (snapshot().evaluation.interruptions.length) {
              <ul class="reasons">
                @for (i of snapshot().evaluation.interruptions; track $index) {
                  <li>{{ name(i.cardId) }}：{{ i.label }}（{{ statusText[i.status] }}{{ i.reason ? '：' + i.reason : '' }}）</li>
                }
              </ul>
            }
          </dd>
          <dt>後續回合資源（靜態估算）</dt>
          <dd>{{ snapshot().evaluation.followUp.total }}（{{ snapshot().evaluation.followUp.basis.join('；') }}）</dd>
        </dl>
      }
    </div>
  `,
  styles: `
    .board { display: flex; flex-direction: column; gap: 6px; max-width: 640px; }
    .grid { display: grid; grid-template-columns: repeat(5, minmax(0, 1fr)); gap: 6px; }
    .grid.st { grid-template-columns: repeat(6, minmax(0, 1fr)); }
    .grid.emz > :nth-child(1) { grid-column: 2; }
    .grid.emz > :nth-child(2) { grid-column: 4; }
    .board { min-width: 0; }
    .cell { position: relative; min-height: 54px; border: 1px dashed var(--border); border-radius: 6px; padding: 14px 3px 3px; display: flex; flex-direction: column; align-items: center; gap: 2px; background: var(--surface); min-width: 0; }
    .cell.empty { background: transparent; opacity: 0.7; }
    .cell.colinked { border: 2px solid var(--ok, #1c7c3f); }
    .slot-name { position: absolute; top: 1px; left: 4px; font-size: 0.65rem; color: var(--muted); }
    .cname { font-size: 0.7rem; text-align: center; overflow-wrap: anywhere; line-height: 1.2; }
    .arrow { position: absolute; font-size: 0.7rem; line-height: 1; color: var(--primary); text-shadow: 0 0 2px #000; }
    .arrow[data-dir='Top'] { top: 1px; left: 50%; transform: translateX(-50%); }
    .arrow[data-dir='Bottom'] { bottom: 1px; left: 50%; transform: translateX(-50%); }
    .arrow[data-dir='Left'] { left: 1px; top: 50%; transform: translateY(-50%); }
    .arrow[data-dir='Right'] { right: 1px; top: 50%; transform: translateY(-50%); }
    .arrow[data-dir='Top-Left'] { top: 1px; left: 1px; }
    .arrow[data-dir='Top-Right'] { top: 1px; right: 1px; }
    .arrow[data-dir='Bottom-Left'] { bottom: 1px; left: 1px; }
    .arrow[data-dir='Bottom-Right'] { bottom: 1px; right: 1px; }
    .colink { position: absolute; bottom: 1px; right: 1px; font-size: 0.6rem; background: var(--ok, #1c7c3f); color: #fff; border-radius: 4px; padding: 0 3px; }
    .compact .grid { gap: 3px; }
    .compact .cell { min-height: 40px; padding: 8px 1px 1px; border-radius: 3px; }
    .compact .slot-name { font-size: 0.5rem; top: 0; left: 2px; }
    .compact .arrow { font-size: 0.5rem; }
    .compact .colink { display: none; }
    .note { margin: 0; font-size: 0.8rem; color: var(--warn); }
    .info { margin: 6px 0 0; font-size: 0.9rem; }
    dt { color: var(--muted); font-size: 0.8rem; margin-top: 6px; }
    dd { margin: 0; min-width: 0; overflow-wrap: anywhere; }
    .reasons { margin: 2px 0 0; padding-left: 1.2em; }
  `,
  changeDetection: ChangeDetectionStrategy.OnPush,
})
export class BoardPreview {
  private readonly labels = inject(CardNamesService);

  readonly snapshot = input.required<BoardSnapshot>();
  readonly cards = input.required<ReadonlyMap<number, CardRecord>>();
  /** Thumbnail: only the zones, tiny cards, no text. */
  readonly compact = input(false);
  readonly label = input('終場預覽（由最後一步的狀態快照產生）');

  protected readonly statusText = { effective: '有效', conditional: '條件未能驗證', inactive: '無效（條件不成立）' } as const;
  protected readonly emz = computed(() => EMZ.map((slot, i) => ({ slot, cell: this.snapshot().emz[i] ?? null })));
  protected readonly mmz = computed(() => MMZ.map((slot, i) => ({ slot, cell: this.snapshot().mmz[i] ?? null })));
  protected readonly st = computed(() => SZ.map((slot, i) => ({ slot, cell: this.snapshot().spellTrap[i] ?? null })));
  protected readonly interruptions = computed(() => interruptionText(this.snapshot().evaluation));
  protected readonly handLabel = computed(() => handText(this.snapshot().evaluation.hand));

  protected glyphOf(marker: string): string {
    return GLYPH[marker as LinkMarker] ?? marker;
  }

  protected name(id: number): string {
    return this.labels.labelOf(id, this.cards().get(id));
  }

  protected names(ids: number[]): string {
    return ids.map((id) => this.name(id)).join('、');
  }

  protected slotLabel(slot: FieldSlot): string {
    return slot === 'FZ' ? '場地' : slot;
  }

  protected total(rows: CardCount[]): number {
    return rows.reduce((s, r) => s + r.count, 0);
  }

  protected list(rows: CardCount[]): string {
    return rows.length ? rows.map((r) => `${this.name(r.cardId)}${r.count > 1 ? `×${r.count}` : ''}`).join('、') : '無';
  }

  protected arrowText(cell: BoardCell): string {
    if (!cell.isLink) return '';
    return `連結箭頭：${cell.arrows.join('、')}；指向 ${cell.pointsTo.join('、') || '（沒有可用的格子）'}${cell.coLinked.length ? `；與 ${cell.coLinked.join('、')} 相互連結` : ''}`;
  }
}
